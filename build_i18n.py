#!/usr/bin/env python3
"""Builds docs/shared/lang/{no,es,de,pt}.js from src/i18n-app/en.txt (master, one English string per line, line number = ID)
and src/i18n-app/t*.txt (lines: ID ¦ no ¦ es ¦ de ¦ pt). Checks IDs and {placeholders}. Run by build.py."""
import glob, json, os, re, sys
ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, "src", "i18n-app")
OUT = os.path.join(ROOT, "docs", "shared", "lang")
LANGS = ["no", "es", "de", "pt"]
ph = lambda s: sorted(re.findall(r"\{\w+\}", s))
norm = lambda s: re.sub(r"\s+", " ", s).strip()

def build(strict=True):
    en = [l.rstrip("\n") for l in open(os.path.join(SRC, "en.txt"), encoding="utf-8")]
    tr = {}
    for f in sorted(glob.glob(os.path.join(SRC, "t*.txt"))):
        for n, l in enumerate(open(f, encoding="utf-8"), 1):
            l = l.rstrip("\n")
            if not l.strip(): continue
            parts = l.split(" ¦ ")
            if len(parts) != 5 or not parts[0].strip().isdigit():
                raise SystemExit(f"{f}:{n}: expected 'ID ¦ no ¦ es ¦ de ¦ pt', got {len(parts)} parts")
            tr[int(parts[0])] = [p.strip() for p in parts[1:]]
    errors, dicts = [], {k: {} for k in LANGS}
    for i, s in enumerate(en, 1):
        if i not in tr: errors.append(f"ID {i} missing: {s[:50]}"); continue
        for lg, t in zip(LANGS, tr[i]):
            if ph(s) != ph(t): errors.append(f"ID {i} [{lg}] placeholders differ: {s[:40]} / {t[:40]}")
            if not t: errors.append(f"ID {i} [{lg}] empty")
            if t != s: dicts[lg][norm(s)] = norm(t) if not t.startswith(".") and not t.startswith(",") and not t.startswith(";") else t.strip()
    for i in tr:
        if i > len(en): errors.append(f"ID {i} has no English master line")
    if any("Mun" + "ken" in s for s in en): errors.append("master mentions the old product name")
    if errors:
        print("\n".join(errors[:40]), file=sys.stderr)
        if strict: raise SystemExit(f"{len(errors)} problems in the app translations")
    os.makedirs(OUT, exist_ok=True)
    for lg, d in dicts.items():
        body = json.dumps(d, ensure_ascii=False, indent=0, sort_keys=True)
        open(os.path.join(OUT, lg + ".js"), "w", encoding="utf-8").write(
            f"// generated by build_i18n.py – do not edit\nwindow.SPK_DICT=window.SPK_DICT||{{}};SPK_DICT.{lg}={body};\n")
    print("app translations:", {lg: len(d) for lg, d in dicts.items()}, "of", len(en))

if __name__ == "__main__":
    build()
